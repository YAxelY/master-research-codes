#!/usr/bin/env python3
"""Regenerate submit-v3.sh from the list of configurations of the notebook.

    IPS_MODE=list python <notebook converted to .py>     # writes run_list.csv
    python tools/make-submit.py <results>/run_list.csv submit-v3.sh

Run it again whenever a configuration is added or removed in the notebook.
"""
import csv
import sys
from collections import OrderedDict

# launch order; 'focus' and 'core' are listed in full, the other groups leave
# out what an earlier group already runs, so nothing is submitted twice
ORDER = ['focus', 'focus_abl', 'focus_m', 'core', 'ablation', 'mstudy',
         'patch', 'base', 'ms', 'lowres', 'hires', 'lowdata', 'misc']
COMPLETE = ('focus', 'core')

names = OrderedDict((row['run'], row['groups'].split('+'))
                    for row in csv.DictReader(open(sys.argv[1])))
groups = OrderedDict()
for g in COMPLETE:
    groups[g] = [n for n, gs in names.items() if g in gs]
seen = set().union(*(set(groups[g]) for g in COMPLETE))
for g in ORDER:
    if g in COMPLETE:
        continue
    groups[g] = [n for n, gs in names.items() if g in gs and n not in seen]
    seen.update(groups[g])
groups = OrderedDict((g, groups[g]) for g in ORDER)

lines = [
    '#!/bin/bash',
    '# =============================================================================',
    '#  submit-v3.sh : one SLURM job per configuration of a group, for one seed.',
    '#  Generated by tools/make-submit.py from the notebook: do not edit by hand.',
    '#',
    '#    bash submit-v3.sh focus 42       selection of 18 November (66/33 DDR, 300/150 RSNA)',
    '#    bash submit-v3.sh focus_abl 42   its ablations: self-attention, random, coarse zones trained',
    '#    bash submit-v3.sh focus_m 42     its values of M',
    '#    bash submit-v3.sh focus 43       same group, another seed',
    '#',
    '#  Groups, in launch order, and number of jobs: '
    + ', '.join(f'{g} {len(v)}' for g, v in groups.items()),
    '#  focus and core are complete; the other lists leave out what an earlier',
    '#  group runs. A model already finished, or running in another job, is',
    '#  skipped by the notebook, so running a command twice is safe.',
    '# =============================================================================',
    'set -euo pipefail',
    'GROUP="${1:?usage: bash submit-v3.sh <group> [seed]}"',
    'SEED="${2:-42}"',
    'case "$GROUP" in',
]
for g, v in groups.items():
    lines.append(f'  {g}) RUNS=({" ".join(v)}) ;;')
lines += [
    '  *) echo "unknown group: $GROUP (' + ' '.join(groups) + ')"; exit 1 ;;',
    'esac',
    'echo "group $GROUP, seed $SEED: ${#RUNS[@]} jobs"',
    'for r in "${RUNS[@]}"; do',
    '  IPS_SEEDS="$SEED" sbatch -J "v3_${r}_s${SEED}" run-ips-suite-v3.sh "$r"',
    'done',
    '',
]
open(sys.argv[2], 'w').write('\n'.join(lines))
for g, v in groups.items():
    print(f'{g:10s} {len(v):3d}  {" ".join(v)[:110]}')
print('total configurations', len(names))
